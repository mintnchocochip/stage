//! Rebuilds `engine/fonts/` (the curated families compiled into Stage), `engine/fonts/catalog.json` and
//! `src/fonts/bundled.rs`. Run from src-tauri: `cargo run --bin fetch-fonts`.

use std::path::Path;

use serde_json::{json, Value};
use stage_lib::fonts::fetch::{agent, download_family};

const CURATED: &[&str] = &[
    // serif
    "fraunces", "newsreader", "source-serif-4", "literata", "instrument-serif", "playfair-display", "eb-garamond", "young-serif",
    // sans
    "instrument-sans", "ibm-plex-sans", "manrope", "dm-sans", "schibsted-grotesk", "figtree", "hanken-grotesk", "onest", "geist",
    "public-sans", "bricolage-grotesque", "archivo",
    // display
    "syne", "unbounded", "big-shoulders-display", "bebas-neue",
    // mono
    "jetbrains-mono", "ibm-plex-mono", "geist-mono", "dm-mono", "space-mono", "fira-code",
];

fn main() -> Result<(), String> {
    let manifest_dir = Path::new(env!("CARGO_MANIFEST_DIR"));
    let out = manifest_dir.join("../engine/fonts");
    let _ = std::fs::remove_dir_all(&out);
    std::fs::create_dir_all(&out).map_err(|e| e.to_string())?;
    let agent = agent();

    let all: Vec<Value> = agent.get("https://api.fontsource.org/v1/fonts").call().and_then(|mut r| r.body_mut().read_json())
        .map_err(|e| format!("catalog: {e}"))?;
    let mut catalog: Vec<Value> = all.iter().filter(|f| f["type"] == "google")
        .map(|f| json!({"id": f["id"], "family": f["family"], "category": f["category"]})).collect();
    catalog.sort_by_key(|f| f["family"].as_str().unwrap_or("").to_lowercase());
    std::fs::write(out.join("catalog.json"), serde_json::to_string(&catalog).unwrap()).map_err(|e| e.to_string())?;
    println!("catalog: {} families", catalog.len());

    let mut rs = String::from("// Generated by `cargo run --bin fetch-fonts`. Do not edit.\npub const BUNDLED: &[(&str, &[u8])] = &[\n");
    for id in CURATED {
        let m = download_family(&agent, id, &out)?;
        let mut files: Vec<String> = std::fs::read_dir(out.join(id)).map_err(|e| e.to_string())?
            .map(|e| e.unwrap().file_name().to_string_lossy().into_owned()).collect();
        files.sort();
        for f in files {
            rs += &format!("    (\"{id}/{f}\", include_bytes!(\"../../../engine/fonts/{id}/{f}\")),\n");
        }
        println!("{id}: {} ({} files)", m.family, m.files.len());
    }
    rs += "];\n";
    std::fs::write(manifest_dir.join("src/fonts/bundled.rs"), rs).map_err(|e| e.to_string())?;
    Ok(())
}
